-- 0003_demo_items.sql
-- First tenant data table of the slice: proves the whole C0 mechanism end to end
-- (id generation, tenant column, index, ENABLE + FORCE row level security, the
-- tenant policy, and the grants the non-owner application role needs).
--
-- ID GENERATION — read this before changing the default:
--   The application generates UUIDv7 (`src/http/ids.ts`) and always sends the id
--   explicitly. The DEFAULT exists so that a row inserted by hand, by a migration,
--   or by a future service that forgets the id is still correct and ordered.
--
--   PostgreSQL 18 ships `uuidv7()` and that is what this project should use once
--   it targets 18. The pinned version is 17 (see `.github/workflows/ci.yml`), so
--   `app_uuid_v7()` below provides an equivalent (restated in full, with its
--   reasoning, in `0004_uuid_v7.sql`). Note that a column DEFAULT is evaluated
--   once at table-creation time and stored as a constant: a
--   `DEFAULT (CASE WHEN to_regprocedure('uuidv7()') IS NOT NULL THEN uuidv7() ELSE ... END)`
--   would freeze one uuid into the catalog and every id-less insert would collide.
--   A function call is evaluated per row, which is why this is a wrapper function.
--
-- MONEY: `numeric(18,4)`, never a float; the driver returns it to Node as a string
-- (docs/CONVENTIONS.md 6) and the API transports that string unchanged.

-- ---------------------------------------------------------------------------
-- app_uuid_v7() — the PostgreSQL 17 stand-in for uuidv7().
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION app_uuid_v7()
RETURNS uuid
LANGUAGE plpgsql
VOLATILE
PARALLEL SAFE
AS $$
DECLARE
  unix_ts_ms bigint;
  rand_bytes bytea;
BEGIN
  unix_ts_ms := floor(extract(epoch FROM clock_timestamp()) * 1000)::bigint;
  rand_bytes := gen_random_bytes(10);

  -- Bytes 0..5: 48-bit big-endian Unix millisecond timestamp.
  rand_bytes := set_byte(rand_bytes, 0, ((unix_ts_ms >> 40) & 255)::int);
  rand_bytes := set_byte(rand_bytes, 1, ((unix_ts_ms >> 32) & 255)::int);
  rand_bytes := set_byte(rand_bytes, 2, ((unix_ts_ms >> 24) & 255)::int);
  rand_bytes := set_byte(rand_bytes, 3, ((unix_ts_ms >> 16) & 255)::int);
  rand_bytes := set_byte(rand_bytes, 4, ((unix_ts_ms >> 8) & 255)::int);
  rand_bytes := set_byte(rand_bytes, 5, (unix_ts_ms & 255)::int);

  -- High nibble of byte 6 = version 7; top two bits of byte 8 = RFC 4122 variant.
  rand_bytes := set_byte(rand_bytes, 6, (get_byte(rand_bytes, 6) & 15) | 112);
  rand_bytes := set_byte(rand_bytes, 8, (get_byte(rand_bytes, 8) & 63) | 128);

  RETURN encode(rand_bytes, 'hex')::uuid;
END
$$;

COMMENT ON FUNCTION app_uuid_v7() IS
  'UUIDv7 (RFC 9562) generator for PostgreSQL 17. Replace with the built-in uuidv7() on PostgreSQL 18.';

GRANT EXECUTE ON FUNCTION app_uuid_v7() TO cheques_app;

-- ---------------------------------------------------------------------------
-- demo_items
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS demo_items (
  id          uuid          NOT NULL DEFAULT app_uuid_v7(),
  tenant_id   uuid          NOT NULL,
  label       text          NOT NULL,
  amount      numeric(18,4) NOT NULL,
  currency    char(3)       NOT NULL,
  status      text          NOT NULL DEFAULT 'draft'
                            CHECK (status IN ('draft', 'confirmed', 'cancelled')),
  created_at  timestamptz   NOT NULL DEFAULT now(),
  updated_at  timestamptz   NOT NULL DEFAULT now(),

  CONSTRAINT demo_items_pkey PRIMARY KEY (id),
  CONSTRAINT demo_items_label_not_blank CHECK (length(btrim(label)) > 0),
  CONSTRAINT demo_items_currency_iso4217 CHECK (currency ~ '^[A-Z]{3}$'),

  -- Redundant with the primary key, but it is the target a child table needs in
  -- order to carry the tenant in its own foreign key (see demo_attachments).
  CONSTRAINT demo_items_id_tenant_key UNIQUE (id, tenant_id)
);

-- Every tenant index starts with tenant_id (docs/CONVENTIONS.md 8), so the policy
-- predicate can be satisfied by an index scan on the tenant prefix.
CREATE INDEX IF NOT EXISTS demo_items_tenant_id_idx ON demo_items (tenant_id);
CREATE INDEX IF NOT EXISTS demo_items_tenant_created_at_idx
  ON demo_items (tenant_id, created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS demo_items_tenant_amount_idx ON demo_items (tenant_id, amount);

COMMENT ON TABLE demo_items IS
  'C0 demo table. Every tenant table follows this shape: tenant_id + index + ENABLE/FORCE RLS + policy.';
COMMENT ON COLUMN demo_items.id IS
  'UUIDv7, generated by the application; the default (app_uuid_v7) covers id-less inserts.';
COMMENT ON COLUMN demo_items.amount IS
  'numeric(18,4) transported as a decimal string; never a JavaScript number.';

-- ---------------------------------------------------------------------------
-- Row level security: ENABLE applies policies to ordinary users, FORCE applies
-- them to the table owner as well. Without FORCE, a role that happened to own the
-- table (for example a migration run by the wrong role) would read every tenant.
-- ---------------------------------------------------------------------------
ALTER TABLE demo_items ENABLE ROW LEVEL SECURITY;
ALTER TABLE demo_items FORCE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS demo_items_tenant_isolation ON demo_items;

CREATE POLICY demo_items_tenant_isolation ON demo_items
  USING (tenant_id = app_current_tenant())
  WITH CHECK (tenant_id = app_current_tenant());

COMMENT ON POLICY demo_items_tenant_isolation ON demo_items IS
  'USING filters reads (and UPDATE/DELETE); WITH CHECK rejects cross-tenant writes.';

-- ---------------------------------------------------------------------------
-- Grants for the non-owner application role. No DDL, no TRUNCATE, no ownership.
-- ---------------------------------------------------------------------------
REVOKE ALL ON TABLE demo_items FROM PUBLIC;
GRANT SELECT, INSERT, UPDATE, DELETE ON TABLE demo_items TO cheques_app;
